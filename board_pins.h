#define BOARD_GRAYSCALE_AD0_PORT          GPIO_GRAYSCALE_AD0_PORT
#define BOARD_GRAYSCALE_AD0_PIN           GPIO_GRAYSCALE_AD0_PIN
#define BOARD_GRAYSCALE_AD1_PORT          GPIO_GRAYSCALE_AD1_PORT
