#define BOARD_GRAYSCALE_AD2_PIN           GPIO_GRAYSCALE_AD2_PIN
#define BOARD_GRAYSCALE_OUT_PORT          GPIO_GRAYSCALE_OUT_PORT
#define BOARD_GRAYSCALE_OUT_PIN           GPIO_GRAYSCALE_OUT_PIN
#define BOARD_GRAYSCALE_OUT_IOMUX         GPIO_GRAYSCALE_OUT_IOMUX

/* 任务按键均为上拉输入、低电平按下：PA29 启动，PA13 切换任务。 */
